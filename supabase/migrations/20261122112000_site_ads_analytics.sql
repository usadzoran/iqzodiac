-- Privacy-preserving ad analytics: public clients can record valid events,
-- while only the existing admin identity can read aggregate results.
create table if not exists public.site_ad_events (
  id bigint generated by default as identity primary key,
  ad_id uuid not null references public.site_ads(id) on delete cascade,
  event_type text not null check (event_type in ('view', 'click')),
  occurred_at timestamptz not null default now(),
  session_key text not null check (char_length(session_key) between 16 and 128)
);

create index if not exists site_ad_events_ad_type_time_idx
  on public.site_ad_events (ad_id, event_type, occurred_at desc);

alter table public.site_ad_events enable row level security;
alter table public.site_ad_events force row level security;
revoke all on table public.site_ad_events from anon, authenticated;

create or replace function public.record_site_ad_event(
  p_ad_id uuid,
  p_event_type text,
  p_session_key text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_event_type not in ('view', 'click')
     or p_session_key is null
     or char_length(p_session_key) < 16
     or char_length(p_session_key) > 128 then
    return;
  end if;

  if not exists (
    select 1 from public.site_ads
    where id = p_ad_id
      and is_active
      and (starts_at is null or starts_at <= now())
      and (ends_at is null or ends_at > now())
  ) then
    return;
  end if;

  -- Keep a single impression per ad/session/day, while allowing real clicks.
  if p_event_type = 'view' and exists (
    select 1 from public.site_ad_events
    where ad_id = p_ad_id
      and event_type = 'view'
      and session_key = p_session_key
      and occurred_at >= date_trunc('day', now())
  ) then
    return;
  end if;

  insert into public.site_ad_events (ad_id, event_type, session_key)
  values (p_ad_id, p_event_type, left(p_session_key, 128));
end;
$$;

grant execute on function public.record_site_ad_event(uuid, text, text) to anon, authenticated;

create or replace function public.iqzodiac_site_ads_analytics()
returns table (
  ad_id uuid,
  name text,
  is_active boolean,
  views bigint,
  clicks bigint,
  ctr numeric
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.iqzodiac_is_admin() then
    return;
  end if;

  return query
  select a.id,
    a.name,
    a.is_active,
    count(e.id) filter (where e.event_type = 'view')::bigint as views,
    count(e.id) filter (where e.event_type = 'click')::bigint as clicks,
    case when count(e.id) filter (where e.event_type = 'view') = 0 then 0
      else round((count(e.id) filter (where e.event_type = 'click')::numeric / count(e.id) filter (where e.event_type = 'view')::numeric) * 100, 2)
    end as ctr
  from public.site_ads a
  left join public.site_ad_events e on e.ad_id = a.id
  group by a.id, a.name, a.is_active
  order by views desc, clicks desc, a.updated_at desc;
end;
$$;

grant execute on function public.iqzodiac_site_ads_analytics() to authenticated;
